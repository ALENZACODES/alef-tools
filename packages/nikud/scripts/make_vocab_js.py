#!/usr/bin/env python3
"""Writes src/vocab.js from the model's tokenizer.json (one character per id; ids 0-5 are the special tokens).
vocab.txt is not used: it holds the line-break character as a real line break and cannot be read back.

    python scripts/make_vocab_js.py <tokenizer.json> src/vocab.js
"""
import json
import sys

src, dst = sys.argv[1], sys.argv[2]
vocab = json.load(open(src, encoding="utf-8"))["model"]["vocab"]
tokens = [t for t, _ in sorted(vocab.items(), key=lambda kv: kv[1])]
assert sorted(vocab.values()) == list(range(len(tokens)))
special = tokens[:6]
assert special == ["[UNK]", "[CLS]", "[SEP]", "[PAD]", "[MASK]", "[BLANK]"], special
chars = tokens[6:]
bad = [(i + 6, t) for i, t in enumerate(chars) if len(t) != 1]
assert not bad, f"not single characters: {bad[:5]}"
assert all(ord(c) < 0x10000 for c in chars)
body = json.dumps("".join(chars), ensure_ascii=True)
open(dst, "w", encoding="utf-8").write(
    "// Generated by scripts/make_vocab_js.py from tokenizer.json of dicta-il/dictabert-large-char-menaked (CC-BY-4.0). Do not edit.\n"
    "// One character per id: the character at index i has id i + 6. Ids 0 to 5 are [UNK] [CLS] [SEP] [PAD] [MASK] [BLANK].\n"
    f"export const FIRST_CHAR_ID = 6;\nexport const CHARS = {body};\n")
print(len(chars), "characters")
