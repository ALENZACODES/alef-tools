// The package as the app receives it: the entry module's shape (docs/CONTRACT.md section 2) and the built data files
// against the size budget and John's rules. Runs from src/ and, with ALEF_TEST_DIST=1, from the built dist/.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const DIR = join(here, '..', process.env.ALEF_TEST_DIST ? 'dist' : 'src');
const pkg = await import(join(DIR, 'index.js'));
const meta = JSON.parse(readFileSync(join(here, '..', 'package.json'), 'utf8'));
const MiB = 1024 * 1024;
const NAME = /י[֑-ׇ]*ה[֑-ׇ]*ו[֑-ׇ]*ה/;
// "AI" is matched in capitals only: Ai is a city in the Torah and belongs in the answers.
const WORDING = /chatgpt|claude|gemini|openai|\bllm\b|language model|machine[- ](generated|written|translated)|dictalm|generated by/i;
const CAPS = /\bAI\b|\bA\.I\./;
const fetchFile = async (url) => {
  const p = fileURLToPath(url);
  if (!existsSync(p)) return { ok: false, status: 404 };
  const buf = readFileSync(p);
  return { ok: true, status: 200, json: async () => JSON.parse(buf.toString('utf8')), arrayBuffer: async () => buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength) };
};
const walk = (d, out = []) => { for (const n of readdirSync(d)) { const p = join(d, n); if (statSync(p).isDirectory()) walk(p, out); else out.push(p); } return out; };

test('entry module has the contract shape, no language pack, and the package version', async () => {
  assert.equal(pkg.id, 'offline-llm');
  assert.equal(pkg.version, meta.version);
  assert.deepEqual(pkg.packs, []);
  assert.equal(typeof pkg.load, 'function');
  assert.equal(typeof pkg.unload, 'function');
  const { definePackage } = await import('../../loader/src/index.js');
  assert.doesNotThrow(() => definePackage(pkg));
  await pkg.unload(); await pkg.unload();
});

test('load() fetches nothing; each call fetches only files of this folder', async () => {
  await pkg.unload();
  const seen = [];
  const api = await pkg.load({ base: 'file://' + DIR + '/', fetch: (u) => { seen.push(String(u)); return fetchFile(u); } });
  assert.deepEqual(seen, []);
  const res = await api.search('what does the torah say about shabbat', { types: ['ask'] });
  assert.ok(res.length >= 1 && res.length <= 3);
  assert.ok(res.some((r) => /shabbat|sabbath/i.test(r.title)), res.map((r) => r.title).join(' | '));
  const he = await api.search('מה התורה אומרת על שבת?', { types: ['ask'] });
  assert.ok(he.some((r) => /shabbat|sabbath/i.test(r.title)), he.map((r) => r.title).join(' | '));
  assert.equal(await api.askExtra('zz no such question'), null);
  const rep = await api.report();
  assert.ok(rep.counts.examples);
  for (const u of seen) assert.ok(u.startsWith('file://' + DIR), u);
  await pkg.unload();
});

test('unitExtras gives empty lists for a unit the build has nothing for (and needs dist.json only in a built folder)', async () => {
  if (!existsSync(join(DIR, 'dist.json'))) return; // src/ has no listing; the built dist/ does
  await pkg.unload();
  const api = await pkg.load({ base: 'file://' + DIR + '/', fetch: fetchFile });
  assert.deepEqual(await api.unitExtras('pu-no-such-unit'), { examples: [], quiz: [] });
  await pkg.unload();
});

test('size budget: search index at most 1.5 MiB in all; each unit file at most 300 KiB', () => {
  const size = (p) => statSync(join(DIR, p)).size;
  assert.ok(size('search/index.v1.json') + size('search/index.v1.vec') <= 1.5 * MiB);
  for (const kind of ['examples', 'quiz']) if (existsSync(join(DIR, kind))) for (const f of readdirSync(join(DIR, kind))) assert.ok(size(`${kind}/${f}`) <= 300 * 1024, f);
});

test('what ships is checked, cites, never spells the Name and says nothing about machines', () => {
  for (const kind of ['examples', 'quiz']) if (existsSync(join(DIR, kind))) for (const f of readdirSync(join(DIR, kind))) {
    const data = JSON.parse(readFileSync(join(DIR, kind, f), 'utf8'));
    assert.ok(data.items.length > 0);
    for (const it of data.items) assert.equal(it.checked, true, `${kind}/${f} ${it.id}`);
  }
  const ask = JSON.parse(readFileSync(join(DIR, 'ask/answers.v1.json'), 'utf8'));
  for (const a of Object.values(ask.answers)) {
    assert.equal(a.checked, true);
    assert.ok(a.passages.length >= 1);
    for (const p of a.passages) assert.ok(p.quote && p.he.includes(p.quote));
  }
  for (const p of walk(DIR)) {
    if (!p.endsWith('.json') || /report\.json$|dist\.json$/.test(p)) continue;
    const text = readFileSync(p, 'utf8');
    assert.doesNotMatch(text, NAME, p);
    const data = JSON.parse(text);
    // what a learner can be shown (not the file's own schema tag, which carries the package name)
    const shown = /search[\\/]index/.test(p) ? data.docs.map((d) => d[2]).join('\n') : JSON.stringify([data.answers, data.questions, data.wordings, data.items]);
    assert.doesNotMatch(shown, WORDING, p);
    assert.doesNotMatch(shown, CAPS, p);
  }
});

test('the report says what was drafted, what passed and what went to review, and nothing unqualified judged', () => {
  const rep = JSON.parse(readFileSync(join(DIR, 'report.json'), 'utf8'));
  for (const k of ['examples', 'quiz', 'ask_answers', 'ask_hebrew_wordings']) {
    const c = rep.counts[k];
    assert.equal(typeof c.generated, 'number'); assert.equal(typeof c.passed_gate, 'number'); assert.equal(typeof c.sent_to_review, 'number');
  }
  const qualified = Object.values(rep.judges).filter((j) => j.qualified).length;
  if (qualified < 2) for (const k of Object.keys(rep.counts)) assert.equal(rep.counts[k].passed_gate, 0, `${k}: nothing can pass without two qualified judges`);
});
