"""Shared helpers for the offline build pipeline. Standard library only, so the gate and its tests run anywhere.

Nothing here loads a model. Hebrew text handling mirrors the app (Al-Heb src/ask/match.js and src/vocab/model.js) so
that a string the gate accepts is compared the same way the app compares it.
"""
from __future__ import annotations

import hashlib
import json
import re
import unicodedata
from pathlib import Path

PKG = Path(__file__).resolve().parent.parent
REPO = PKG.parent.parent
MANIFEST = PKG / "models.json"  # this lane's working details (keys, files, GGUF names); the shared list is /models.manifest.json

# Hebrew points and cantillation (U+0591..U+05C7) and maqaf (U+05BE).
_POINTS = re.compile(r"[֑-ֽֿ-ׇ]")
_HEB = re.compile(r"[א-ת]")
_HEB_WORD = re.compile(r"[א-ת][א-ת\"'׳״]*")
# The four-letter Name, with any points between the letters. Written with escapes on purpose.
_NAME = re.compile("י[֑-ׇ]*ה[֑-ׇ]*ו[֑-ׇ]*ה[֑-ׇ]*")
NAME_SHOWN = "ה׳"  # he + geresh, the only way the Name is shown
_FINALS = str.maketrans("ךםןףץ", "כמנפצ")
PREFIX_LETTERS = "והבלמשכ"  # vav he bet lamed mem shin kaf

# Words that must never reach a learner-facing string (hard rule 6). Checked on English text, case-insensitive,
# except "AI", which is matched in capitals only: Ai is a city in the Torah.
_AI_WORDING = re.compile(
    r"\b((?-i:AI|A\.I\.?)|artificial intelligence|language model|llm|chatbot|chat ?gpt|gpt|neural|machine[- ](?:generated|written|learning|translated)|"
    r"generated by|auto[- ]?generated|as an? (?:ai|assistant)|dictalm|berel|dictabert|prompt)\b",
    re.I,
)


def strip_points(s: str) -> str:
    """Remove vowel points and cantillation; turn maqaf into a space."""
    s = unicodedata.normalize("NFD", str(s or ""))
    return unicodedata.normalize("NFC", _POINTS.sub("", s).replace("־", " "))


def he_key(s: str) -> str:
    """A comparison key for Hebrew text: no points, no punctuation, final letters folded, single spaces."""
    s = strip_points(s).translate(_FINALS)
    return " ".join(_HEB_WORD.findall(s))


def he_words(s: str) -> list[str]:
    return _HEB_WORD.findall(strip_points(s))


def has_hebrew(s: str) -> bool:
    return bool(_HEB.search(str(s or "")))


def name_spelled(s: str) -> bool:
    """True when the four-letter Name is written out anywhere in the text."""
    return bool(_NAME.search(unicodedata.normalize("NFD", str(s or ""))))


def show_name(s: str) -> str:
    """The text as the app shows it: the Name replaced by the he-geresh form."""
    out = _NAME.sub(NAME_SHOWN, unicodedata.normalize("NFD", str(s or "")))
    return unicodedata.normalize("NFC", out)


def ai_wording(s: str) -> list[str]:
    """Learner-facing wording that hard rule 6 forbids, as the matched fragments (empty list = clean)."""
    return [m.group(0) for m in _AI_WORDING.finditer(str(s or ""))]


def unprefixed(word: str) -> list[str]:
    """The word and its forms with one or two one-letter prefixes removed (longest stem first kept >= 2 letters)."""
    out = [word]
    for n in (1, 2):
        if len(word) - n >= 2 and all(c in PREFIX_LETTERS for c in word[:n]):
            out.append(word[n:])
    return out


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def stable_id(*parts: str) -> str:
    return hashlib.sha256("\x1f".join(parts).encode("utf-8")).hexdigest()[:10]


def read_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def write_json(path, data, *, compact=False):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        if compact:
            json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
        else:
            json.dump(data, f, ensure_ascii=False, indent=1)
        f.write("\n")


def read_jsonl(path) -> list[dict]:
    p = Path(path)
    if not p.exists():
        return []
    with open(p, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def write_jsonl(path, rows):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")


def manifest_model(key: str) -> dict:
    """One model entry from this package's models.json by its short key."""
    for m in read_json(MANIFEST)["models"]:
        if m.get("key") == key:
            return m
    raise KeyError(f"model key {key!r} is not in {MANIFEST}")


# ---------------------------------------------------------------- app data (read-only views of an Al-Heb checkout)

LEVEL_ORDER = ["L0", "L1", "L2", "L3", "L4"]
# Dictionary band a unit level may draw on (data/vocab/packs tiers), on top of the words of its own and earlier units.
LEVEL_TIER = {"L0": 500, "L1": 1000, "L2": 2000, "L3": 5000, "L4": 5000}
BOOKS = ["genesis", "exodus", "leviticus", "numbers", "deuteronomy"]
BOOK_EN = {b: b.capitalize() for b in BOOKS}


class App:
    """Read-only access to the parts of an Al-Heb checkout this pipeline builds from."""

    def __init__(self, root):
        self.root = Path(root)
        if not (self.root / "data" / "curriculum" / "practical" / "index.json").exists():
            raise FileNotFoundError(f"{root} does not look like an Al-Heb checkout")
        self._cache: dict = {}

    def json(self, rel):
        if rel not in self._cache:
            self._cache[rel] = read_json(self.root / rel)
        return self._cache[rel]

    def units(self) -> list[dict]:
        return self.json("data/curriculum/practical/index.json")["units"]

    def unit(self, unit_id: str) -> dict:
        return self.json(f"data/curriculum/practical/{unit_id}.json")

    def vocab_tier(self, tier: int) -> list[dict]:
        return self.json(f"data/vocab/packs/vocab5k-tier-{tier}.json")["entries"]

    def verse(self, verse_id: str) -> dict | None:
        """{'he','en','ref','id'} for an id such as genesis.1.1, or None when the app has no such verse."""
        m = re.fullmatch(r"([a-z]+)\.(\d+)\.(\d+)", verse_id or "")
        if not m or m.group(1) not in BOOKS:
            return None
        book, ch, v = m.group(1), int(m.group(2)), int(m.group(3))
        p = self.root / "data" / "corpus" / "torah" / book / f"{ch:02d}.json"
        if not p.exists():
            return None
        for row in self.json(f"data/corpus/torah/{book}/{ch:02d}.json")["verses"]:
            if int(row["n"]) == v:
                return {"id": verse_id, "ref": f"{BOOK_EN[book]} {ch}:{v}", "he": row["he"], "en": row["en"]}
        return None

    def verses(self):
        idx = self.json("data/corpus/torah/index.json")
        for b in idx["books"]:
            for ch in range(1, b["chapters"] + 1):
                p = f"data/corpus/torah/{b['id']}/{ch:02d}.json"
                if not (self.root / p).exists():
                    continue
                for row in self.json(p)["verses"]:
                    yield {"id": f"{b['id']}.{ch}.{row['n']}", "ref": f"{b['en']} {ch}:{row['n']}", "he": row["he"], "en": row["en"]}

    def allowed_words(self, level: str) -> set[str]:
        """he_key forms a sentence for a unit of this level may use: words of every unit at or below the level,
        plus the dictionary band for the level (lemmas and their listed forms)."""
        key = ("allowed", level)
        if key in self._cache:
            return self._cache[key]
        top = LEVEL_ORDER.index(level)
        words: set[str] = set()
        for u in self.units():
            if LEVEL_ORDER.index(u["level"]) <= top:
                for it in self.unit(u["id"]).get("items", []):
                    words.update(he_key(it.get("he", "")).split())
        for tier in (500, 1000, 2000, 5000):
            if tier > LEVEL_TIER[level]:
                break
            for e in self.vocab_tier(tier):
                words.update(he_key(e.get("lemma", "")).split())
                for f in e.get("forms") or []:
                    words.update(he_key(f.get("he", "")).split())
        self._cache[key] = words
        return words

    def existing_sentences(self) -> set[str]:
        """he_key of every Hebrew line the app already teaches (unit items and dictionary examples)."""
        if "existing" in self._cache:
            return self._cache["existing"]
        seen: set[str] = set()
        for u in self.units():
            for it in self.unit(u["id"]).get("items", []):
                seen.add(he_key(it.get("he", "")))
        words = self.root / "data" / "vocab" / "words.json"
        if words.exists():
            data = self.json("data/vocab/words.json")
            rows = data.get("words") or data.get("entries") or [] if isinstance(data, dict) else data
            for w in rows:
                for ex in (w.get("examples") or ([w["example"]] if w.get("example") else [])):
                    if isinstance(ex, dict) and ex.get("he"):
                        seen.add(he_key(ex["he"]))
        seen.discard("")
        self._cache["existing"] = seen
        return seen
